const assert = require('node:assert/strict'), fs = require('node:fs'), vm = require('node:vm');
const context = {window:{APP_LOCALE:'en-US'}, Intl}; vm.createContext(context);
vm.runInContext(fs.readFileSync(__dirname+'/../../js/renter-format.js','utf8'),context);
const {format,plot,exact} = context.window.renterFormat;
assert.equal(format('1000000000','bytes'),'1 GB');
assert.equal(format('18446744073709551615','bytes'),'18.45 EB');
assert.equal(exact('18446744073709551615','bytes'),'18446744073709551615 bytes');
assert.equal(format('1000000000000000000000000','money'),'1 SC');
assert.equal(format('1234567890000000000000000','money'),'1.2346 SC');
assert.equal(format('1','money'),'<0.0001 SC');
assert.equal(format(null,'money'),'Unavailable');
assert.equal(format('0','money'),'0 SC');
assert.equal(format('144','duration'),'1 day');
assert.equal(format('4320','duration'),'1 month');
assert.equal(format('0.5','duration'),'5 minutes');
assert.equal(format('2','duration',{average_contract_duration:'days'}),'2 days');
assert.equal(format('1.5','money',{money:'sc'}),'1.5 SC');
assert.equal(plot('1000000000000000000000000','money'),1);
assert.equal(plot('144','duration'),1);
assert.equal(plot(null,'duration'),null);
assert.equal(format('99999999999999999999999999999999999999999999999999','money'),'100,000,000,000,000,000,000,000,000 SC');
console.log('PASS renter storage, SC, duration, precision, null and chart conversions');
